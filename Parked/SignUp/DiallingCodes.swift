    /// ISO 3166-1 alpha-2.
    let region: String
    /// Digits, without the plus.
    let code: String

    var id: String { region }

    var name: String {
        Format.locale.localizedString(forRegionCode: region) ?? region
    }

    /// Regional indicator symbols: the two letters shifted into the flag block.
    var flag: String {
        String(String.UnicodeScalarView(region.unicodeScalars.compactMap {
            Unicode.Scalar(127_397 + $0.value)
        }))
    }

    /// What goes in front of the number.
    var prefix: String { "+" + code }

    /// The reader's own country if the table has it, otherwise the busiest one
    /// that is not a guess about them.
    static var current: DiallingCode {
        let region = Locale.current.region?.identifier
        return all.first { $0.region == region } ?? all.first { $0.region == "US" } ?? all[0]
    }

    static func named(_ region: String) -> DiallingCode? {
        all.first { $0.region == region }
    }

    /// Sorted the way they are read, in the language they are read in.
    static var sortedByName: [DiallingCode] {
        all.sorted { $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }
    }

