//
//  DiallingCodes.swift
//  Relays
//
//  A phone number only means something with a country in front of it. The form
//  asked for one field and hoped, which works for whoever wrote it and nobody
//  else.
//
//  The table is ISO 3166-1 codes to ITU calling codes, derived from the
//  mledoze/countries dataset. Countries whose calling code covers several
//  territories keep the shared root: the United States and Canada are both 1,
//  Russia and Kazakhstan both 7. Country names are not in here — the system
//  knows them in the reader's language, and this app has its own language
//  setting to ask with.
//

